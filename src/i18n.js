export function t(language, englishSource, values = {}) {
  const template = language === 'en' ? englishSource : CS[englishSource] ?? englishSource;
  return template.replace(/\{(\w+)\}/g, (placeholder, key) => Object.hasOwn(values, key) ? String(values[key]) : placeholder);
}

export function placeName(language, englishName) {
  return t(language, englishName);
}
